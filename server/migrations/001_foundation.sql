-- ============================================================================
-- Robokalam Learner OS — Migration 001: Phase 1 Foundation (MySQL 8 / MariaDB 10.6+)
-- Tenancy, auth, RBAC, catalog, master learner DB, parents, batches,
-- learner/teacher batch memberships, activity timeline, audit log.
--
-- Core invariant: ONE learner = ONE row in `learners`. Batch participation is
-- expressed ONLY through `learner_batch_memberships` (unique learner_id+batch_id).
-- Every business table carries org_id and composite foreign keys (id, org_id)
-- prevent cross-tenant references at the database level.
--
-- MySQL notes: ids are VARCHAR(36) UUIDs generated by the application; "partial"
-- unique indexes are emulated with STORED generated columns that are NULL when the
-- rule does not apply (a UNIQUE index ignores NULLs); times are UTC DATETIME(3).
-- ============================================================================

CREATE TABLE organizations (
  id            VARCHAR(36) NOT NULL PRIMARY KEY,
  name          VARCHAR(160) NOT NULL,
  slug          VARCHAR(50) NOT NULL,
  code_prefix   VARCHAR(6) NOT NULL DEFAULT 'RK',
  timezone      VARCHAR(60) NOT NULL DEFAULT 'Asia/Kolkata',
  status        VARCHAR(12) NOT NULL DEFAULT 'active',
  settings      JSON NULL,
  created_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at    DATETIME(3) NULL,
  UNIQUE KEY uq_organizations_slug (slug),
  CONSTRAINT chk_org_slug CHECK (slug COLLATE utf8mb4_bin REGEXP '^[a-z0-9][a-z0-9-]{1,48}$'),
  CONSTRAINT chk_org_prefix CHECK (code_prefix COLLATE utf8mb4_bin REGEXP '^[A-Z0-9]{2,6}$'),
  CONSTRAINT chk_org_status CHECK (status IN ('active','suspended','archived'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Per-organization counters for human readable ids (RK-LRN-000124).
CREATE TABLE org_counters (
  org_id       VARCHAR(36) NOT NULL,
  counter_key  VARCHAR(40) NOT NULL,
  value        BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (org_id, counter_key),
  CONSTRAINT fk_counters_org FOREIGN KEY (org_id) REFERENCES organizations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE branches (
  id          VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id      VARCHAR(36) NOT NULL,
  name        VARCHAR(160) NOT NULL,
  code        VARCHAR(20) NOT NULL,
  city        VARCHAR(100) NULL,
  address     VARCHAR(400) NULL,
  status      VARCHAR(12) NOT NULL DEFAULT 'active',
  created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at  DATETIME(3) NULL,
  UNIQUE KEY uq_branches_org_code (org_id, code),
  UNIQUE KEY uq_branches_id_org (id, org_id),
  CONSTRAINT fk_branches_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT chk_branch_status CHECK (status IN ('active','inactive','archived'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Identity & RBAC
-- ---------------------------------------------------------------------------
CREATE TABLE users (
  id                   VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id               VARCHAR(36) NULL,                            -- NULL only for platform super admins
  email                VARCHAR(190) NOT NULL,
  mobile               VARCHAR(20) NULL,
  password_hash        VARCHAR(255) NOT NULL,
  full_name            VARCHAR(160) NOT NULL,
  status               VARCHAR(12) NOT NULL DEFAULT 'active',
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  failed_login_count   INT NOT NULL DEFAULT 0,
  locked_until         DATETIME(3) NULL,
  last_login_at        DATETIME(3) NULL,
  created_at           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at           DATETIME(3) NULL,
  email_key            VARCHAR(190) GENERATED ALWAYS AS (IF(deleted_at IS NULL, email, NULL)) STORED,
  UNIQUE KEY uq_users_email (email_key),
  UNIQUE KEY uq_users_id_org (id, org_id),
  KEY idx_users_org (org_id),
  KEY idx_users_mobile (mobile),
  CONSTRAINT fk_users_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT chk_user_status CHECK (status IN ('active','disabled','invited'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE roles (
  id           VARCHAR(36) NOT NULL PRIMARY KEY,
  code         VARCHAR(40) NOT NULL,
  name         VARCHAR(80) NOT NULL,
  description  VARCHAR(255) NULL,
  is_system    BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE KEY uq_roles_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE permissions (
  id           VARCHAR(36) NOT NULL PRIMARY KEY,
  code         VARCHAR(60) NOT NULL,
  description  VARCHAR(255) NULL,
  UNIQUE KEY uq_permissions_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE role_permissions (
  role_id        VARCHAR(36) NOT NULL,
  permission_id  VARCHAR(36) NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- A user can hold several roles; branch_id optionally narrows the scope of a role.
CREATE TABLE user_roles (
  id          VARCHAR(36) NOT NULL PRIMARY KEY,
  user_id     VARCHAR(36) NOT NULL,
  role_id     VARCHAR(36) NOT NULL,
  org_id      VARCHAR(36) NULL,
  branch_id   VARCHAR(36) NULL,
  created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  branch_key  VARCHAR(36) GENERATED ALWAYS AS (IF(branch_id IS NULL, role_id, branch_id)) STORED,
  UNIQUE KEY uq_user_roles (user_id, role_id, branch_key),
  KEY idx_user_roles_user (user_id),
  CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES roles(id),
  CONSTRAINT fk_ur_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_ur_branch FOREIGN KEY (branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE auth_sessions (
  id                  VARCHAR(36) NOT NULL PRIMARY KEY,
  user_id             VARCHAR(36) NOT NULL,
  refresh_token_hash  VARCHAR(64) NOT NULL,
  user_agent          VARCHAR(300) NULL,
  ip                  VARCHAR(64) NULL,
  expires_at          DATETIME(3) NOT NULL,
  revoked_at          DATETIME(3) NULL,
  created_at          DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_sessions_hash (refresh_token_hash),
  KEY idx_auth_sessions_user (user_id),
  CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
