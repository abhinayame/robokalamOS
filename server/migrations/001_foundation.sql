  OR (r.code = 'branch_admin' AND p.code IN ('catalog:read','catalog:manage','user:manage','teacher:read','learner:read','learner:create','learner:update','learner:delete','learner:export','learner:bulk','learner:login','parent:read','parent:manage','batch:read','batch:create','batch:update','batch:enroll','batch:assign_teacher','selection:resolve','dashboard:view','audit:read'))
  OR (r.code = 'teacher' AND p.code IN ('catalog:read','teacher:read','learner:read','parent:read','batch:read','selection:resolve','dashboard:view'))
  OR (r.code = 'counsellor' AND p.code IN ('catalog:read','teacher:read','learner:read','learner:create','learner:update','learner:export','parent:read','parent:manage','batch:read','batch:enroll','selection:resolve','dashboard:view'))
  OR (r.code = 'accountant' AND p.code IN ('catalog:read','learner:read','parent:read','batch:read','dashboard:view'))
  OR (r.code = 'learner' AND p.code IN ('portal:learner','dashboard:view'))
  OR (r.code = 'parent' AND p.code IN ('portal:parent','dashboard:view'));
