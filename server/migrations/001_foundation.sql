-- ---------------------------------------------------------------------------
-- People: parents and the MASTER learner table
-- ---------------------------------------------------------------------------
CREATE TABLE parents (
  id          VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id      VARCHAR(36) NOT NULL,
  user_id     VARCHAR(36) NULL,
  full_name   VARCHAR(160) NOT NULL,
  mobile      VARCHAR(20) NULL,
  email       VARCHAR(190) NULL,
  created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at  DATETIME(3) NULL,
  mobile_key  VARCHAR(20) GENERATED ALWAYS AS (IF(deleted_at IS NULL, mobile, NULL)) STORED,
  UNIQUE KEY uq_parents_id_org (id, org_id),
  -- Siblings share ONE parent record: a parent mobile is unique per organization.
  UNIQUE KEY uq_parents_org_mobile (org_id, mobile_key),
  KEY idx_parents_org_email (org_id, email),
  KEY idx_parents_user (user_id),
  CONSTRAINT fk_parents_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_parents_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE learners (
  id             VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id         VARCHAR(36) NOT NULL,
  branch_id      VARCHAR(36) NULL,
  user_id        VARCHAR(36) NULL,
  learner_code   VARCHAR(30) NOT NULL,                -- e.g. RK-LRN-000124 (immutable)
  full_name      VARCHAR(160) NOT NULL,
  mobile         VARCHAR(20) NULL,                    -- normalised: +91XXXXXXXXXX
  email          VARCHAR(190) NULL,
  date_of_birth  DATE NULL,
  gender         VARCHAR(12) NULL,
  school         VARCHAR(200) NULL,
  location       VARCHAR(200) NULL,
  photo_url      VARCHAR(500) NULL,
  status         VARCHAR(12) NOT NULL DEFAULT 'active',
  enrolled_on    DATE NOT NULL DEFAULT (CURRENT_DATE),
  created_by     VARCHAR(36) NULL,
  created_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at     DATETIME(3) NULL,
  mobile_key     VARCHAR(20) GENERATED ALWAYS AS (IF(deleted_at IS NULL, mobile, NULL)) STORED,
  email_key      VARCHAR(190) GENERATED ALWAYS AS (IF(deleted_at IS NULL, email, NULL)) STORED,
  UNIQUE KEY uq_learners_org_code (org_id, learner_code),
  UNIQUE KEY uq_learners_id_org (id, org_id),
  UNIQUE KEY uq_learners_org_mobile (org_id, mobile_key),
  UNIQUE KEY uq_learners_org_email (org_id, email_key),
  KEY idx_learners_org_status (org_id, status),
  KEY idx_learners_org_name (org_id, full_name, id),
  KEY idx_learners_org_created (org_id, created_at, id),
  KEY idx_learners_org_enrolled (org_id, enrolled_on),
  KEY idx_learners_branch (branch_id),
  KEY idx_learners_user (user_id),
  CONSTRAINT fk_learners_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_learners_branch FOREIGN KEY (branch_id, org_id) REFERENCES branches (id, org_id),
  CONSTRAINT fk_learners_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_learners_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT chk_learner_status CHECK (status IN ('active','inactive','archived')),
  CONSTRAINT chk_learner_gender CHECK (gender IS NULL OR gender IN ('female','male','other','undisclosed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE learner_parents (
  learner_id    VARCHAR(36) NOT NULL,
  parent_id     VARCHAR(36) NOT NULL,
  org_id        VARCHAR(36) NOT NULL,
  relationship  VARCHAR(30) NOT NULL DEFAULT 'guardian',
  is_primary    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  primary_key_  VARCHAR(36) GENERATED ALWAYS AS (IF(is_primary, learner_id, NULL)) STORED,
  PRIMARY KEY (learner_id, parent_id),
  UNIQUE KEY uq_learner_primary_parent (primary_key_),
  KEY idx_learner_parents_parent (parent_id),
  CONSTRAINT fk_lp_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_lp_learner FOREIGN KEY (learner_id, org_id) REFERENCES learners (id, org_id),
  CONSTRAINT fk_lp_parent FOREIGN KEY (parent_id, org_id) REFERENCES parents (id, org_id)
