-- ---------------------------------------------------------------------------
-- Batches and memberships
-- ---------------------------------------------------------------------------
CREATE TABLE batches (
  id             VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id         VARCHAR(36) NOT NULL,
  branch_id      VARCHAR(36) NULL,
  program_id     VARCHAR(36) NOT NULL,
  course_id      VARCHAR(36) NOT NULL,
  batch_code     VARCHAR(30) NOT NULL,                  -- e.g. RK-BAT-0042
  name           VARCHAR(160) NOT NULL,
  academic_year  VARCHAR(20) NOT NULL,                  -- e.g. 2026-27
  start_date     DATE NULL,
  end_date       DATE NULL,
  schedule       JSON NULL,                             -- {days:[1,3], start:"17:00", end:"18:30", mode:"online"}
  capacity       INT NULL,
  status         VARCHAR(12) NOT NULL DEFAULT 'upcoming',
  created_by     VARCHAR(36) NULL,
  created_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at     DATETIME(3) NULL,
  UNIQUE KEY uq_batches_org_code (org_id, batch_code),
  UNIQUE KEY uq_batches_id_org (id, org_id),
  KEY idx_batches_org_status (org_id, status),
  KEY idx_batches_course (course_id),
  KEY idx_batches_program (program_id),
  KEY idx_batches_branch (branch_id),
  KEY idx_batches_year (org_id, academic_year),
  CONSTRAINT fk_batches_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_batches_branch FOREIGN KEY (branch_id, org_id) REFERENCES branches (id, org_id),
  CONSTRAINT fk_batches_program FOREIGN KEY (program_id, org_id) REFERENCES programs (id, org_id),
  CONSTRAINT fk_batches_course FOREIGN KEY (course_id, org_id) REFERENCES courses (id, org_id),
  CONSTRAINT fk_batches_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT chk_batch_status CHECK (status IN ('upcoming','active','completed','archived')),
  CONSTRAINT chk_batch_capacity CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT chk_batch_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- THE learner ↔ batch relationship. One row per (learner, batch), ever.
-- Re-joining a batch re-activates the same row; history lives in learner_activity.
CREATE TABLE learner_batch_memberships (
  id           VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id       VARCHAR(36) NOT NULL,
  learner_id   VARCHAR(36) NOT NULL,
  batch_id     VARCHAR(36) NOT NULL,
  status       VARCHAR(12) NOT NULL DEFAULT 'active',
  joined_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  left_at      DATETIME(3) NULL,
  left_reason  VARCHAR(200) NULL,
  enrolled_by  VARCHAR(36) NULL,
  created_at   DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at   DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_learner_batch (learner_id, batch_id),
  KEY idx_lbm_batch_status (batch_id, status),
  KEY idx_lbm_learner_status (learner_id, status),
  KEY idx_lbm_org (org_id),
  CONSTRAINT fk_lbm_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_lbm_learner FOREIGN KEY (learner_id, org_id) REFERENCES learners (id, org_id),
  CONSTRAINT fk_lbm_batch FOREIGN KEY (batch_id, org_id) REFERENCES batches (id, org_id),
  CONSTRAINT fk_lbm_enrolled_by FOREIGN KEY (enrolled_by) REFERENCES users(id),
  CONSTRAINT chk_lbm_status CHECK (status IN ('active','completed','left','transferred'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE teacher_batch_memberships (
  id               VARCHAR(36) NOT NULL PRIMARY KEY,
  org_id           VARCHAR(36) NOT NULL,
  batch_id         VARCHAR(36) NOT NULL,
  teacher_user_id  VARCHAR(36) NOT NULL,
  role             VARCHAR(8) NOT NULL DEFAULT 'lead',
  status           VARCHAR(8) NOT NULL DEFAULT 'active',
  assigned_at      DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  removed_at       DATETIME(3) NULL,
  assigned_by      VARCHAR(36) NULL,
  lead_key         VARCHAR(36) GENERATED ALWAYS AS (IF(role = 'lead' AND status = 'active', batch_id, NULL)) STORED,
  UNIQUE KEY uq_teacher_batch (batch_id, teacher_user_id),
  -- At most one active lead teacher per batch.
  UNIQUE KEY uq_tbm_one_lead (lead_key),
  KEY idx_tbm_teacher_status (teacher_user_id, status),
  KEY idx_tbm_batch_status (batch_id, status),
  CONSTRAINT fk_tbm_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_tbm_batch FOREIGN KEY (batch_id, org_id) REFERENCES batches (id, org_id),
  CONSTRAINT fk_tbm_teacher FOREIGN KEY (teacher_user_id, org_id) REFERENCES users (id, org_id),
  CONSTRAINT fk_tbm_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(id),
  CONSTRAINT chk_tbm_role CHECK (role IN ('lead','co')),
  CONSTRAINT chk_tbm_status CHECK (status IN ('active','removed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Learner activity timeline & audit log
-- ---------------------------------------------------------------------------
CREATE TABLE learner_activity (
  id             BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  org_id         VARCHAR(36) NOT NULL,
  learner_id     VARCHAR(36) NOT NULL,
  batch_id       VARCHAR(36) NULL,
  type           VARCHAR(40) NOT NULL,        -- learner.created, batch.joined, batch.left, batch.transferred_in, ...
  title          VARCHAR(255) NOT NULL,
  description    VARCHAR(500) NULL,
  meta           JSON NULL,
  actor_user_id  VARCHAR(36) NULL,
  occurred_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_activity_learner_time (learner_id, occurred_at, id),
  KEY idx_activity_org_time (org_id, occurred_at),
  CONSTRAINT fk_activity_org FOREIGN KEY (org_id) REFERENCES organizations(id),
  CONSTRAINT fk_activity_learner FOREIGN KEY (learner_id, org_id) REFERENCES learners (id, org_id),
  CONSTRAINT fk_activity_actor FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

